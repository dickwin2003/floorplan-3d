function chairs(cx,cy,r,n,off=0){
  return Array.from({length:n},(_,i)=>{
    const a = off + i*2*Math.PI/n;
    return {t:'chair',n:'餐椅',x:Math.round(cx+r*Math.cos(a)),y:Math.round(cy+r*Math.sin(a)),w:450,d:480,rot:Math.round(90+a*180/Math.PI)};
  });
}

